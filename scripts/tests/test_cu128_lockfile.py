"""Checks for the pinned CUDA 12.8 lockfile requirements/cu128-py312.txt (run: python -m pytest scripts/tests).

The lockfile is generated by scripts/lock_cu128.sh. It is resolved only: no install or run from it is
recorded yet. These tests keep it consistent with the pyproject.toml files and with the CPU lockfile's
generator, reusing the parser and the declared-range check from test_cpu_lockfile.py.
"""

import importlib.util
import re
from pathlib import Path

from packaging.utils import canonicalize_name
from packaging.version import Version

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
LOCK = ROOT / "requirements" / "cu128-py312.txt"
SCRIPT = ROOT / "scripts" / "lock_cu128.sh"
CPU_SCRIPT = ROOT / "scripts" / "lock_cpu.sh"

_spec = importlib.util.spec_from_file_location("cpu_lock_checks", HERE / "test_cpu_lockfile.py")
cpu = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(cpu)


def compile_args(script):
    """The uv pip compile options of a lock script, joined across continuation lines."""
    text = re.sub(r"\\\n\s*", " ", script.read_text())
    return re.search(r"uv pip compile (.*?)\)\"", text, flags=re.S).group(1).split()


def test_every_pin_is_exact_and_hashed():
    pins = cpu.parse_lock(LOCK.read_text())
    assert pins, "lockfile has no pins"
    assert [name for name, (_, n) in pins.items() if n == 0] == []


def test_header_names_generator_date_and_cu128_index():
    head = LOCK.read_text().splitlines()[:5]
    assert any("scripts/lock_cu128.sh" in line and "resolution date" in line for line in head)
    options = [line for line in LOCK.read_text().splitlines() if line.startswith("--")]
    assert options == ["--index-url https://pypi.org/simple",
                       "--extra-index-url https://download.pytorch.org/whl/cu128"]


def test_script_matches_cpu_script_except_backend():
    # Same packages, extras, target and resolution date as the CPU lock; only the torch backend differs.
    assert re.findall(r"^\s+(\S+/pyproject\.toml)\s*$", SCRIPT.read_text(), flags=re.M) == cpu.locked_pyprojects()
    cu, cp = compile_args(SCRIPT), compile_args(CPU_SCRIPT)
    assert [a for a in cu if a != "cu128"] == [a for a in cp if a != "cpu"]
    assert cu[cu.index("--torch-backend") + 1] == "cu128"
    date = re.compile(r'EXCLUDE_NEWER="\$\{EXCLUDE_NEWER:-([^}]+)\}"')
    assert date.search(SCRIPT.read_text()).group(1) == date.search(CPU_SCRIPT.read_text()).group(1)


def test_every_declared_dependency_is_pinned_inside_its_range():
    pins = cpu.parse_lock(LOCK.read_text())
    problems = []
    for rel, req in cpu.declared_requirements():
        if req.marker is not None and not req.marker.evaluate(cpu.TARGET_ENV):
            continue
        name = canonicalize_name(req.name)
        if name.startswith("awen-"):
            continue
        if name not in pins:
            problems.append(f"{rel}: {req} not pinned")
        elif not req.specifier.contains(pins[name][0], prereleases=True):
            problems.append(f"{rel}: {req} but lockfile pins {pins[name][0]}")
    assert problems == []


def test_torch_is_a_cu128_build_new_enough_for_sm_120():
    # The project brief requires PyTorch 2.7 or newer built for CUDA 12.8 or newer on sm_120.
    version, _ = cpu.parse_lock(LOCK.read_text())["torch"]
    assert version.local == "cu128"
    assert Version(version.public) >= Version("2.7")


def test_cuda_runtime_libraries_are_the_12_8_line():
    pins = cpu.parse_lock(LOCK.read_text())
    runtime = pins["nvidia-cuda-runtime-cu12"][0]
    assert (runtime.major, runtime.minor) == (12, 8)
