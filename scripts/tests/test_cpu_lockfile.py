"""Checks for the pinned CPU lockfile requirements/cpu-py312.txt (run: python -m pytest scripts/tests).

The lockfile is generated by scripts/lock_cpu.sh. These tests keep it consistent with the
pyproject.toml files it was resolved from: every pin is exact and hashed, every declared
dependency is pinned, and every pin satisfies the declared range.
"""

import re
import tomllib
from pathlib import Path

from packaging.requirements import Requirement
from packaging.utils import canonicalize_name
from packaging.version import Version

ROOT = Path(__file__).resolve().parents[2]
LOCK = ROOT / "requirements" / "cpu-py312.txt"
SCRIPT = ROOT / "scripts" / "lock_cpu.sh"
# Extras resolved into the lockfile, per scripts/lock_cpu.sh.
LOCKED_EXTRAS = ("test", "frameworks")
TARGET_ENV = {"python_version": "3.12", "python_full_version": "3.12.0", "sys_platform": "linux",
              "platform_system": "Linux", "platform_machine": "x86_64", "implementation_name": "cpython",
              "platform_python_implementation": "CPython", "os_name": "posix"}


def parse_lock(text):
    """Return {canonical name: (Version, hash count)} from a hashed requirements file."""
    pins = {}
    for entry in re.sub(r"\\\n\s*", " ", text).splitlines():
        entry = entry.strip()
        if not entry or entry.startswith(("#", "--")):
            continue
        spec, *hashes = entry.split(" --hash=")
        match = re.fullmatch(r"([A-Za-z0-9._-]+)==([^\s;]+)", spec.strip())
        assert match, f"not an exact pin: {spec!r}"
        pins[canonicalize_name(match.group(1))] = (Version(match.group(2)), len(hashes))
    return pins


def locked_pyprojects():
    return re.findall(r"^\s+(\S+/pyproject\.toml)\s*$", SCRIPT.read_text(), flags=re.M)


def declared_requirements():
    reqs = []
    for rel in locked_pyprojects():
        project = tomllib.loads((ROOT / rel).read_text())["project"]
        names = list(project.get("dependencies", []))
        for extra in LOCKED_EXTRAS:
            names += project.get("optional-dependencies", {}).get(extra, [])
        reqs += [(rel, Requirement(r)) for r in names]
    return reqs


def test_parse_lock_rejects_unpinned():
    try:
        parse_lock("numpy>=1.26\n")
    except AssertionError:
        return
    raise AssertionError("range pin was accepted")


def test_parse_lock_reads_hashes_and_local_versions():
    pins = parse_lock("torch==2.14.1+cpu \\\n    --hash=sha256:aa \\\n    --hash=sha256:bb\n    # via x\n")
    assert pins == {"torch": (Version("2.14.1+cpu"), 2)}


def test_every_pin_is_exact_and_hashed():
    pins = parse_lock(LOCK.read_text())
    assert pins, "lockfile has no pins"
    assert [name for name, (_, n) in pins.items() if n == 0] == []


def test_header_names_generator_date_and_cpu_index():
    head = LOCK.read_text().splitlines()[:5]
    assert any("scripts/lock_cpu.sh" in line and "resolution date" in line for line in head)
    assert "--extra-index-url https://download.pytorch.org/whl/cpu" in head


def test_index_url_comes_before_extra_index_url():
    # pip applies index options line by line: an --index-url after --extra-index-url drops the
    # extra index, and then the +cpu torch wheel is not found (seen on 2026-10-29).
    options = [line.split()[0] for line in LOCK.read_text().splitlines() if line.startswith("--")]
    assert options == ["--index-url", "--extra-index-url"]


def test_script_covers_every_python_package():
    found = sorted(str(p.relative_to(ROOT)) for p in ROOT.glob("*/pyproject.toml"))
    found += sorted(str(p.relative_to(ROOT)) for p in ROOT.glob("*/python_*/pyproject.toml"))
    assert sorted(locked_pyprojects()) == sorted(found)


def test_every_declared_dependency_is_pinned_inside_its_range():
    pins = parse_lock(LOCK.read_text())
    problems = []
    for rel, req in declared_requirements():
        if req.marker is not None and not req.marker.evaluate(TARGET_ENV):
            continue
        name = canonicalize_name(req.name)
        if name.startswith("awen-"):
            continue  # AWEN packages are installed from the checkout, not the lockfile
        if name not in pins:
            problems.append(f"{rel}: {req} not pinned")
        elif not req.specifier.contains(pins[name][0], prereleases=True):
            problems.append(f"{rel}: {req} but lockfile pins {pins[name][0]}")
    assert problems == []


def test_torch_pin_is_the_cpu_build():
    version, _ = parse_lock(LOCK.read_text())["torch"]
    assert version.local == "cpu"
