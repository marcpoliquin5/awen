#!/usr/bin/env bash
# Regenerate requirements/cpu-py312.txt, the pinned CPU lockfile for every AWEN Python package.
# Scope: runtime dependencies plus the `test` extras of all eight packages and the `frameworks`
# extra of awen-ecosystem, resolved for CPython 3.12 on x86_64 Linux with CPU-only PyTorch wheels.
# EXCLUDE_NEWER fixes the resolution date so a rerun gives the same pins; change it on purpose only.
set -euo pipefail
cd "$(dirname "$0")/.."
EXCLUDE_NEWER="${EXCLUDE_NEWER:-2026-10-29T00:00:00Z}"
OUT=requirements/cpu-py312.txt
PYPROJECTS=(
  awen-ecosystem/python_awen/pyproject.toml
  awen-models/pyproject.toml
  awen-native/pyproject.toml
  awen-physics/pyproject.toml
  awen-qphotonic/pyproject.toml
  awen-systems/pyproject.toml
  awen-lab/pyproject.toml
  awen-studio/pyproject.toml
)
body="$(uv pip compile "${PYPROJECTS[@]}" \
  --extra test --extra frameworks \
  --python-version 3.12 --python-platform x86_64-manylinux_2_28 \
  --torch-backend cpu --exclude-newer "$EXCLUDE_NEWER" \
  --generate-hashes --no-header --quiet)"
{
  echo "# Pinned CPU lockfile for AWEN's Python packages (CPython 3.12, x86_64 Linux, CPU-only PyTorch)."
  echo "# Generated by scripts/lock_cpu.sh with uv, resolution date $EXCLUDE_NEWER. Do not edit by hand."
  echo "# Install: python -m pip install --require-hashes -r requirements/cpu-py312.txt (see docs/install.md)."
  # pip applies index options line by line, so --index-url must come before --extra-index-url.
  echo "--index-url https://pypi.org/simple"
  echo "--extra-index-url https://download.pytorch.org/whl/cpu"
  printf '%s\n' "$body"
} > "$OUT"
echo "wrote $OUT"
