#!/usr/bin/env bash
# Regenerate requirements/cu129-py312.txt, the pinned CUDA 12.9 lockfile for every AWEN Python package.
# Scope: runtime dependencies plus the `test` extras of all eight packages and the `frameworks`
# extra of awen-ecosystem, resolved for CPython 3.12 on x86_64 Linux with PyTorch wheels built for
# CUDA 12.9 (cu129). The project brief requires cu128 or newer for Blackwell sm_120 GPUs (the RTX 5070 Ti
# laptop target). Not cu128: its newest torch (2.11.0) caps setuptools below 82, and setuptools before 83 has
# advisory GHSA-h35f-9h28-mq5c (moderate), which the required gate's dependency review rejects. Resolved only: no install or run from this lockfile is recorded yet (no GPU on the build box).
# EXCLUDE_NEWER fixes the resolution date so a rerun gives the same pins; change it on purpose only.
set -euo pipefail
cd "$(dirname "$0")/.."
EXCLUDE_NEWER="${EXCLUDE_NEWER:-2026-10-29T00:00:00Z}"
OUT=requirements/cu129-py312.txt
PYPROJECTS=(
  awen-ecosystem/python_awen/pyproject.toml
  awen-models/pyproject.toml
  awen-native/pyproject.toml
  awen-physics/pyproject.toml
  awen-qphotonic/pyproject.toml
  awen-systems/pyproject.toml
  awen-lab/pyproject.toml
  awen-studio/pyproject.toml
)
body="$(uv pip compile "${PYPROJECTS[@]}" \
  --extra test --extra frameworks \
  --python-version 3.12 --python-platform x86_64-manylinux_2_28 \
  --torch-backend cu129 --exclude-newer "$EXCLUDE_NEWER" \
  --generate-hashes --no-header --quiet)"
{
  echo "# Pinned CUDA 12.9 lockfile for AWEN's Python packages (CPython 3.12, x86_64 Linux, PyTorch cu129)."
  echo "# Generated by scripts/lock_cu129.sh with uv, resolution date $EXCLUDE_NEWER. Do not edit by hand."
  echo "# Install: python -m pip install --require-hashes -r requirements/cu129-py312.txt (see docs/install.md)."
  # pip applies index options line by line, so --index-url must come before --extra-index-url.
  echo "--index-url https://pypi.org/simple"
  echo "--extra-index-url https://download.pytorch.org/whl/cu129"
  printf '%s\n' "$body"
} > "$OUT"
echo "wrote $OUT"
